module PhysicalOffsetReferenceTests
using Test, FilterGraphAlgorithms, LinearAlgebra
import FilterGraphAlgorithms: process!, replace_parameter!, reset!

function fixture(; sign=-1f0, residual_count=3, physical_count=4, mode_count=2)
    return prepare_algorithm(PhysicalOffsetReferenceF32,
        PhysicalOffsetReferenceF32Configuration(;residual_count, physical_count, mode_count,
            reference_sign=sign, residual_schema="test.residual/1", physical_schema="test.physical/1",
            physical_to_modes_schema="test.physical-to-modes/1", modes_to_reference_schema="test.modes-to-reference/1"))
end
const Q = Float32[1 0 2 0; 0 1 0 -1]
const C = Float32[1 2; -1 0; 0 3]
const OFFSET = Float32[2,-1,0.5,1]
function calibrate!(p)
    replace_parameter!(p,Symbol("physical-to-modes"),Q)
    replace_parameter!(p,Symbol("modes-to-reference"),C)
    return p
end
allocated_step(y,o,p,x)=@allocated process!(y,o,p,x)

@testset "physical offset reference factorization and atomic outputs" begin
    p=fixture();x=Float32[10,20,30];y=fill(99f0,3);o=fill(99f0,4)
    @test PhysicalOffsetReferenceF32 in algorithms()
    @test process!(y,o,p,x)===nothing
    @test y==x && o==zeros(Float32,4)
    calibrate!(p)
    offset=copy(OFFSET)
    replace_parameter!(p,:offset,offset); fill!(offset,99)
    @test process!(y,o,p,x)===nothing
    @test y==x-C*(Q*OFFSET) && o==OFFSET
    @test allocated_step(y,o,p,x)==0
    # A disturbance generated by this physical offset cancels for either
    # calibrated sign, with the physical offset read back from the same Plan.
    for sign in (-1f0,1f0)
        pp=calibrate!(fixture(;sign))
        replace_parameter!(pp,:offset,OFFSET)
        residual=-sign.*(C*(Q*OFFSET))
        @test process!(y,o,pp,residual)===nothing
        @test y==zeros(Float32,3) && o==OFFSET
    end
    previous_plan=p.plan
    replacement=Float32[-1,2,0,0]
    replace_parameter!(p,:offset,replacement)
    @test p.plan!==previous_plan
    @test previous_plan.offset==OFFSET
    @test previous_plan.correction==-C*(Q*OFFSET)
    @test process!(y,o,p,x)===nothing
    @test y==x-C*(Q*replacement) && o==replacement
    # Replacing a factor recomputes compensation for the retained offset.
    changed_c=2f0.*C
    replace_parameter!(p,Symbol("modes-to-reference"),changed_c)
    @test process!(y,o,p,x)===nothing
    @test y==x-changed_c*(Q*replacement) && o==replacement
    replace_parameter!(p,Symbol("modes-to-reference"),C)
    reset!(p)
    @test process!(y,o,p,x)===nothing
    @test y==x-C*(Q*replacement) && o==replacement
    replace_parameter!(p,:offset,zeros(Float32,4))
    @test process!(y,o,p,x)===nothing
    @test y==x && o==zeros(Float32,4)
end

@testset "calibration copy, shape, nonfinite and overflow rejection" begin
    p=calibrate!(fixture()); x=Float32[1,2,3]; y=zeros(Float32,3); o=zeros(Float32,4)
    replace_parameter!(p,:offset,OFFSET)
    @test process!(y,o,p,x)===nothing
    old=p.plan; old_y=copy(y); old_o=copy(o)
    for (name,values) in ((:offset,Float32[NaN,0,0,0]),
            (Symbol("physical-to-modes"),fill(Inf32,2,4)),
            (Symbol("modes-to-reference"),fill(NaN32,3,2)),
            (:offset,fill(floatmax(Float32),4)))
        @test_throws ArgumentError replace_parameter!(p,name,values)
        @test p.plan===old
        @test process!(y,o,p,x)===nothing
        @test y==old_y && o==old_o
    end
    for (name,values) in ((:offset,zeros(Float32,3)),
            (Symbol("physical-to-modes"),zeros(Float32,4,2)),
            (Symbol("modes-to-reference"),zeros(Float32,2,3)))
        @test_throws DimensionMismatch replace_parameter!(p,name,values)
        @test p.plan===old
    end
    q=copy(Q); c=copy(C)
    replace_parameter!(p,Symbol("physical-to-modes"),q)
    replace_parameter!(p,Symbol("modes-to-reference"),c)
    fill!(q,NaN32);fill!(c,NaN32)
    @test process!(y,o,p,x)===nothing
    @test y==old_y && o==old_o
    for value in (NaN32,Inf32,-Inf32)
        bad=copy(x);bad[2]=value
        @test process!(y,o,p,bad)===VectorLinearCombinationNonFiniteInput
        @test y==old_y && o==old_o
    end
    # Finite factor/offset replacement can still create finite corrections
    # whose sum with a finite residual overflows. Neither output may publish.
    pp=calibrate!(fixture(;sign=1f0))
    replace_parameter!(pp,Symbol("modes-to-reference"),Float32[1 0; 0 0; 0 0])
    replace_parameter!(pp,:offset,Float32[floatmax(Float32),0,0,0])
    @test process!(y,o,pp,fill(floatmax(Float32),3))===VectorLinearCombinationNonFiniteOutput
    @test y==old_y && o==old_o
    @test_throws ArgumentError fixture(;sign=0f0)
    @test_throws ArgumentError fixture(;sign=NaN32)
    @test_throws ArgumentError fixture(;physical_count=0)
    @test_throws ArgumentError fixture(;mode_count=0)
end

@testset "port identity, metadata and alias boundaries" begin
    p=calibrate!(fixture());x=Float32[1,2,3];y=zeros(Float32,3);o=zeros(Float32,4)
    ports=algorithm_ports(PhysicalOffsetReferenceF32)
    @test getproperty.(ports,:name)==(Symbol("reconstructed-residual"),Symbol("compensated-residual"),
        Symbol("physical-offset"),:offset,Symbol("physical-to-modes"),Symbol("modes-to-reference"))
    @test ports[2].metadata_source===ports[3].metadata_source===Symbol("reconstructed-residual")
    @test getproperty.(algorithm_formats(p),:shape)==((3,),(3,),(4,),(4,),(2,4),(3,2))
    @test_throws DimensionMismatch process!(y,zeros(Float32,3),p,x)
    @test_throws DimensionMismatch process!(zeros(Float32,2),o,p,x)
    @test_throws DimensionMismatch process!(y,o,p,zeros(Float32,2))
    shared=zeros(Float32,7)
    @test_throws ArgumentError process!(view(shared,1:3),view(shared,3:6),p,x)
    @test_throws ArgumentError process!(x,o,p,x)
    @test_throws ArgumentError process!(y,p.plan.offset,p,x)
    @test_throws ArgumentError process!(p.plan.correction,o,p,x)
    @test_throws ArgumentError process!(view(p.plan.physical_to_modes,1:3),o,p,x)
    @test_throws ArgumentError process!(p.workspace.candidate_output,o,p,x)
end
@testset "instrument dimensions retain factored calibration and allocation budget" begin
    p=fixture(;residual_count=1509,physical_count=2304,mode_count=8)
    q=zeros(Float32,8,2304);c=zeros(Float32,1509,8)
    for i in 1:8
        q[i,i]=1f0
        c[i,i]=2f0
    end
    replace_parameter!(p,Symbol("physical-to-modes"),q)
    replace_parameter!(p,Symbol("modes-to-reference"),c)
    offset=fill(0.25f0,2304);replace_parameter!(p,:offset,offset)
    x=ones(Float32,1509);y=similar(x);o=similar(offset)
    @test process!(y,o,p,x)===nothing
    @test y[1:8]==fill(0.5f0,8) && y[9:end]==ones(Float32,1501)
    @test o==offset
    @test allocated_step(y,o,p,x)==0
    @test size(p.plan.physical_to_modes)==(8,2304)
    @test size(p.plan.modes_to_reference)==(1509,8)
end

end
